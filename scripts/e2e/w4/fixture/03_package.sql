-- @statement
CREATE OR REPLACE PACKAGE PKG_W4_&run_id AS
    FUNCTION PURE_FN(P_ID NUMBER) RETURN NUMBER;
    PROCEDURE DML_PROC(P_ID NUMBER);
    PROCEDURE DDL_PROC;
    PROCEDURE AUTO_PROC(P_ID NUMBER);
    FUNCTION POLICY_FN(P_SCHEMA VARCHAR2, P_OBJECT VARCHAR2) RETURN VARCHAR2;
END;
-- @statement
CREATE OR REPLACE PACKAGE BODY PKG_W4_&run_id AS
    FUNCTION PURE_FN(P_ID NUMBER) RETURN NUMBER IS
    BEGIN
        RETURN P_ID + 1;
    END;

    PROCEDURE DML_PROC(P_ID NUMBER) IS
    BEGIN
        INSERT INTO T_PARENT_&run_id(ID, LABEL) VALUES (P_ID, 'procedure');
    END;

    PROCEDURE DDL_PROC IS
    BEGIN
        EXECUTE IMMEDIATE 'CREATE TABLE T_PROC_&run_id (ID NUMBER)';
    END;

    PROCEDURE AUTO_PROC(P_ID NUMBER) IS
        PRAGMA AUTONOMOUS_TRANSACTION;
    BEGIN
        INSERT INTO T_AUTO_&run_id(ID) VALUES (P_ID);
        COMMIT;
    END;

    FUNCTION POLICY_FN(P_SCHEMA VARCHAR2, P_OBJECT VARCHAR2) RETURN VARCHAR2 IS
    BEGIN
        RETURN 'ID >= 0';
    END;
END;
